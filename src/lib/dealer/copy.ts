function fillLineTemplate(
  raw: string,
  covenant: string,
  combo = 0,
  targetName = '这一格',
): string {
  return raw
    .replace(/\$C/g, covenant)
    .replace(/\$N/g, String(combo))
    .replace(/\$O/g, targetName);
}

export function pickLine(
  lines: readonly string[],
  seed: number,
  covenant: string,
  combo = 0,
  targetName = '这一格',
): string {
  const raw = lines[Math.abs(seed) % lines.length];
  return fillLineTemplate(raw, covenant, combo, targetName);
}

export function pickBySeed(items: readonly string[], seed: number): string {
  return items[Math.abs(seed) % items.length];
}

export function replayShuffleLine(seed: number): string {
  return REPLAY_SHUFFLE_LINES[Math.abs(seed) % REPLAY_SHUFFLE_LINES.length];
}

export function reactionLine(
  event: 'hit' | 'miss' | 'ultimate' | 'clear',
  covenant: string,
  combo: number,
  seed: number,
  target?: {readonly name: string},
): string {
  const targetName = target?.name ?? '这一格';
  if (event === 'ultimate') {
    return pickLine(ULTIMATE_LINES, seed, covenant, combo, targetName);
  }
  if (event === 'clear') {
    return pickLine(CLEAR_LINES, seed, covenant, combo, targetName);
  }
  if (event === 'miss') {
    return pickLine(MISS_LINES, seed, covenant, combo, targetName);
  }
  if (combo >= 3) {
    return pickLine(COMBO_LINES, seed, covenant, combo, targetName);
  }
  return pickLine(HIT_LINES, seed, covenant, combo, targetName);
}
