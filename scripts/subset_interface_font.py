"""Group shipped interface characters into one local display-font subset.

Run after changing UI text or season data: python scripts/subset_interface_font.py
Requires fonttools[woff] (see requirements-fonts.txt); normal builds need no Python.
Reads the existing vendored WOFF2 files, preserving their outlines and license.
"""

from hashlib import sha256
from io import BytesIO
import json
from pathlib import Path
import re
from tempfile import TemporaryDirectory

from fontTools import subset
from fontTools.merge import Merger
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / 'public/assets/fonts'
CSS_PATH = ROOT / 'public/assets/css/fonts.css'
FAMILY = 'ZCOOL QingKe HuangYou'
MARKER = '/* Interface subset generated by scripts/subset_interface_font.py */'


def interface_codepoints():
    """Collect all shipped text, including lazy routes and season names.

    Including source comments is intentionally conservative: newly added labels
    remain covered without maintaining a separate hand-written character list.
    """
    paths = list(ROOT.glob('*.html'))
    for directory in ('src', 'data'):
        paths.extend(path for path in (ROOT / directory).rglob('*')
                     if path.suffix in {'.ts', '.vue', '.html'})
    return set(range(32, 127)).union(
        *(set(map(ord, path.read_text(encoding='utf-8'))) for path in paths)
    )


def unicode_ranges(codepoints):
    """Return compact CSS ranges for a nonempty set of Unicode code points."""
    ranges = []
    start = end = None
    for value in sorted(codepoints):
        if end is not None and value == end + 1:
            end = value
            continue
        if start is not None:
            ranges.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
        start = end = value
    if start is not None:
        ranges.append(f'U+{start:X}' if start == end else f'U+{start:X}-{end:X}')
    return ', '.join(ranges)


def main():
    """Write one content-hashed font and disjoint CSS ranges; fail on data loss."""
    css = CSS_PATH.read_text(encoding='utf-8').split(MARKER)[0].rstrip() + '\n'
    rules = re.findall(r'@font-face\s*\{[^}]+\}', css)
    display_rules = [rule for rule in rules if f"'{FAMILY}'" in rule]
    # A source shard may have been entirely absorbed by the UI subset on the
    # previous run. Recover its declaration from the vendoring manifest too.
    manifest = json.loads((FONT_DIR / 'sources.json').read_text(encoding='utf-8'))
    for source in sorted(set(manifest['files'].values())):
        if not source.startswith('zcoolqingkehuangyou-'):
            continue
        if any(source in rule for rule in display_rules):
            continue
        rule = (f"@font-face {{\n  font-family: '{FAMILY}';\n"
                '  font-style: normal;\n  font-weight: 400;\n  font-display: swap;\n'
                f"  src: url(../fonts/{source}) format('woff2');\n"
                '  unicode-range: U+0-10FFFF;\n}')
        display_rules.append(rule)
        css += rule + '\n'
    requested = interface_codepoints()
    covered = set()
    original_maps = {}

    with TemporaryDirectory(prefix='wsq-interface-font-') as directory:
        parts = []
        # CSS's last matching face wins when source subsets overlap.
        for rule in reversed(display_rules):
            filename = re.search(r'url\(\.\./fonts/([^)]+)\)', rule).group(1)
            font = TTFont(FONT_DIR / filename, recalcTimestamp=False)
            original_maps[filename] = set(font.getBestCmap())
            selected = (original_maps[filename] & requested) - covered
            if not selected:
                font.close()
                continue
            options = subset.Options()
            options.recalc_timestamp = False
            subsetter = subset.Subsetter(options=options)
            subsetter.populate(unicodes=selected)
            subsetter.subset(font)
            font.flavor = None
            path = Path(directory) / f'{len(parts)}.ttf'
            font.save(path)
            font.close()
            parts.append(str(path))
            covered.update(selected)

        merged = Merger().merge(parts)
        merged.recalcTimestamp = False
        if set(merged.getBestCmap()) != covered:
            raise ValueError('Merged interface font lost or added characters')
        merged.flavor = 'woff2'
        output = BytesIO()
        merged.save(output)
        binary = output.getvalue()

    filename = f'zcoolqingkehuangyou-ui-{sha256(binary).hexdigest()[:16]}.woff2'
    (FONT_DIR / filename).write_bytes(binary)
    for rule in display_rules:
        source = re.search(r'url\(\.\./fonts/([^)]+)\)', rule).group(1)
        remaining = original_maps[source] - covered
        # Keep original source files so regeneration remains completely offline.
        replacement = re.sub(r'unicode-range:[^;]+;',
                             f'unicode-range: {unicode_ranges(remaining)};', rule)
        css = css.replace(rule, replacement if remaining else '')
    css += (f'\n{MARKER}\n@font-face {{\n'
            f"  font-family: '{FAMILY}';\n"
            '  font-style: normal;\n  font-weight: 400;\n  font-display: swap;\n'
            f"  src: url(../fonts/{filename}) format('woff2');\n"
            f'  unicode-range: {unicode_ranges(covered)};\n}}\n')
    CSS_PATH.write_text(css, encoding='utf-8', newline='\n')
    print(f'Interface font: {len(covered)} characters, {len(binary):,} bytes, {filename}')


if __name__ == '__main__':
    main()
