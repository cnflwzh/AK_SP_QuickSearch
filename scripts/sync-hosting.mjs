/** Regenerate the checked-in host rules from the same paths used by Vue Router. */
import {readFileSync, writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {APP_PATHS, PAGE_PATHS} from '../src/router/paths.ts';

const root = resolve(import.meta.dirname, '..');
const routes = APP_PATHS.flatMap((path) => [path, path + '/']);
const noCache = {'Cache-Control': 'no-cache'};
const immutable = {'Cache-Control': 'public, max-age=31536000, immutable'};
const headers = [
  [
    '/*',
    {
      'X-Content-Type-Options': 'nosniff',
      'Referrer-Policy': 'strict-origin-when-cross-origin',
    },
  ],
  ['/assets/bundles/*', immutable],
  ['/assets/fonts/*.woff2', immutable],
  ['/assets/img/*', {'Cache-Control': 'public, max-age=2592000'}],
  ['/assets/icons/*', {'Cache-Control': 'public, max-age=604800'}],
  ['/sw.js', noCache],
  ['/*.webmanifest', {...noCache, 'Content-Type': 'application/manifest+json'}],
  ['/', noCache],
  // 只给已发布的根路径加页面规则，避免托管端为 SW 和 manifest 拼接重复的缓存指令。
  ...[
    ...APP_PATHS.filter((path) => !path.slice(1).includes('/')),
    '/guide', '/diff', '/404', '/*.html', '/LICENSE',
  ].map((path) => [path, noCache]),
  ['/:page/', noCache],
  ...[PAGE_PATHS.bd, PAGE_PATHS.cv, PAGE_PATHS.ld].map((path) => [
    path + '/*',
    noCache,
  ]),
];
const redirects =
  '# Generated by scripts/sync-hosting.mjs. Missing assets retain their HTTP 404.\n' +
  routes.map((path) => path + ' / 200').join('\n') +
  '\n';
const cloudHeaders =
  '# Generated by scripts/sync-hosting.mjs.\n' +
  headers
    .map(([path, fields]) =>
      [
        path,
        ...Object.entries(fields).map(([key, value]) => `  ${key}: ${value}`),
      ].join('\n'),
    )
    .join('\n') +
  '\n';
const edgeFile = resolve(root, 'edgeone.json');
const edge = JSON.parse(readFileSync(edgeFile, 'utf8'));
edge.rewrites = [
  ...['guide', 'diff'].flatMap((page) =>
    [`/${page}`, `/${page}/`].map((source) => ({
      source,
      destination: `/${page}.html`,
    })),
  ),
  ...routes.map((source) => ({source, destination: '/index.html'})),
];
edge.headers = headers.map(([source, fields]) => ({
  source,
  headers: Object.entries(fields).map(([key, value]) => ({key, value})),
}));
const files = new Map([
  ['public/_redirects', redirects],
  ['public/_headers', cloudHeaders],
  ['edgeone.json', JSON.stringify(edge, null, 2) + '\n'],
]);

/** Fail a build with stale host rules before emitting a site with inconsistent navigation. */
export function checkHostingRules() {
  for (const [name, wanted] of files) {
    if (
      readFileSync(resolve(root, name), 'utf8').replaceAll('\r\n', '\n') !==
      wanted
    )
      throw new Error(`Stale ${name}. Run node scripts/sync-hosting.mjs.`);
  }
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  for (const [name, content] of files)
    writeFileSync(resolve(root, name), content);
}
